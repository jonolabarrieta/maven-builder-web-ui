package net.olaba.mvnbuilder.service;

import net.olaba.mvnbuilder.entities.*;
import org.hibernate.SessionFactory;
import org.hibernate.cfg.Configuration;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import java.nio.file.Path;
import java.sql.DriverManager;
import java.util.*;
import static org.junit.jupiter.api.Assertions.*;

/** Opens a real legacy H2 file, upgrades it, closes Hibernate and reopens it. */
class WorkspaceGroupsPersistenceTest {
    @TempDir Path directory;
    SessionFactory factory(String url) {
        return new Configuration().addAnnotatedClass(Workspace.class).addAnnotatedClass(MavenProject.class)
            .addAnnotatedClass(JavaInstallation.class).addAnnotatedClass(WorkspaceProjectGroup.class)
            .setProperty("hibernate.connection.url",url).setProperty("hibernate.connection.username","sa")
            .setProperty("hibernate.connection.password","").setProperty("hibernate.hbm2ddl.auto","update")
            .setProperty("hibernate.show_sql","false").buildSessionFactory();
    }
    @Test void legacyWorkspaceAndSharedGroupSurviveActualDatabaseReopen() throws Exception {
        String url="jdbc:h2:file:"+directory.resolve("legacy")+";DB_CLOSE_ON_EXIT=FALSE";
        try(var connection=DriverManager.getConnection(url,"sa","");var statement=connection.createStatement()) {
            statement.execute("CREATE TABLE workspace (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(255) NOT NULL, base_path VARCHAR(2000), java_installation_id BIGINT)");
            statement.execute("INSERT INTO workspace(id,name) VALUES (42,'Legacy')");
        }
        long groupId, projectId, consumerId;
        try(var factory=factory(url); var session=factory.openSession()) {
            var tx=session.beginTransaction(); Workspace legacy=session.get(Workspace.class,42L);
            assertEquals(WorkspaceKind.NORMAL,legacy.getKind()); assertTrue(legacy.getBlocks().isEmpty());
            Workspace parent=Workspace.builder().withName("Shared").withKind(WorkspaceKind.PARENT).build(); session.persist(parent);
            Workspace consumer=Workspace.builder().withName("Consumer").build(); session.persist(consumer);
            MavenProject project=MavenProject.builder().withArtifactId("Folder").withAbsolutePath(directory.toString())
                .withRelativePath(".").withProjectKind(ProjectKind.FOLDER).withEnabled(false).withExecutionOrder(3).withWorkspace(parent).build();
            session.persist(project);
            WorkspaceProjectGroup group=new WorkspaceProjectGroup(); group.setWorkspace(consumer); group.setParentWorkspace(parent); group.setName("Imported");
            group.getEnabledOverrides().put(project.getId(),true); session.persist(group);
            consumer.getBlocks().add("g:"+group.getId());
            groupId=group.getId(); projectId=project.getId(); consumerId=consumer.getId(); tx.commit();
        }
        try(var factory=factory(url);var session=factory.openSession()) {
            var tx=session.beginTransaction();
            var group=session.get(WorkspaceProjectGroup.class,groupId);
            assertTrue(group.isImported()); assertEquals(WorkspaceKind.PARENT,group.getParentWorkspace().getKind());
            assertEquals(List.of("g:"+groupId),session.get(Workspace.class,consumerId).getBlocks());
            assertEquals(true,group.getEnabledOverrides().get(projectId));
            var source=session.get(MavenProject.class,projectId); assertFalse(source.isEnabled());
            assertEquals(ProjectKind.FOLDER,source.getProjectKind()); assertEquals(3,source.getExecutionOrder());
            assertEquals(WorkspaceKind.NORMAL,session.get(Workspace.class,42L).getKind()); tx.commit();
        }
    }
}
